func TestBuildIdempotentInsert(t *testing.T) {
	tests := []struct {
		name           string
		table          string
		columns        []string
		conflictTarget string
		updateColumns  []string
		want           string
	}{
		{
			name:           "unconditional ignore DO NOTHING",
			table:          "roles",
			columns:        []string{"name"},
			conflictTarget: "",
			want:           `INSERT INTO "roles" ("name") VALUES ... ON CONFLICT DO NOTHING;`,
		},
		{
			name:           "targeted ignore with conflict target DO NOTHING",
			table:          "users",
			columns:        []string{"id", "email"},
			conflictTarget: "id",
			want:           `INSERT INTO "users" ("id", "email") VALUES ... ON CONFLICT ("id") DO NOTHING;`,
		},
		{
			name:           "upsert updating single column",
			table:          "users",
			columns:        []string{"id", "name"},
			conflictTarget: "id",
			updateColumns:  []string{"name"},
			want:           `INSERT INTO "users" ("id", "name") VALUES ... ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name";`,
		},
		{
			name:           "upsert updating multiple columns",
			table:          "users",
			columns:        []string{"id", "name", "email"},
			conflictTarget: "id",
			updateColumns:  []string{"name", "email"},
			want:           `INSERT INTO "users" ("id", "name", "email") VALUES ... ON CONFLICT ("id") DO UPDATE SET "name" = EXCLUDED."name", "email" = EXCLUDED."email";`,
		},
		{
			name:           "handles already quoted table and columns",
			table:          `"accounts"`,
			columns:        []string{`"id"`, `"balance"`},
			conflictTarget: `"id"`,
			want:           `INSERT INTO "accounts" ("id", "balance") VALUES ... ON CONFLICT ("id") DO NOTHING;`,
		},
		{
			name:           "composite conflict target",
			table:          "memberships",
			columns:        []string{"org_id", "user_id", "role"},
			conflictTarget: "org_id, user_id",
			updateColumns:  []string{"role"},
			want:           `INSERT INTO "memberships" ("org_id", "user_id", "role") VALUES ... ON CONFLICT ("org_id", "user_id") DO UPDATE SET "role" = EXCLUDED."role";`,
		},
		{
			name:           "empty columns",
			table:          "counters",
			columns:        nil,
			conflictTarget: "",
			want:           `INSERT INTO "counters" VALUES ... ON CONFLICT DO NOTHING;`,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := grizzle.BuildIdempotentInsert(tt.table, tt.columns, tt.conflictTarget, tt.updateColumns...)
			if got != tt.want {
				t.Fatalf("BuildIdempotentInsert() mismatch:\n got:  %s\n want: %s", got, tt.want)
			}
		})
	}
}

func TestLintSeed(t *testing.T) {
	t.Run("safe patterns generated by BuildIdempotentInsert", func(t *testing.T) {
		inserts := []string{
			grizzle.BuildIdempotentInsert("roles", []string{"name"}, ""),
			grizzle.BuildIdempotentInsert("users", []string{"id", "email"}, "id"),
			grizzle.BuildIdempotentInsert("users", []string{"id", "name", "email"}, "id", "name", "email"),
		}
		for _, stmt := range inserts {
			diags := grizzle.LintSeed(stmt)
			if len(diags) != 0 {
				t.Errorf("expected 0 diagnostics for statement %q, got: %+v", stmt, diags)
			}
		}
	})

	t.Run("safe dialect patterns pass cleanly", func(t *testing.T) {
		safeSQL := `
			INSERT OR IGNORE INTO settings (key, val) VALUES ('theme', 'dark');
			INSERT OR REPLACE INTO flags (name, enabled) VALUES ('beta', 1);
			INSERT INTO users (id, name) SELECT 1, 'admin' WHERE NOT EXISTS (SELECT 1 FROM users WHERE id = 1);
			DELETE FROM sessions WHERE expired_at < CURRENT_TIMESTAMP;
		`
		diags := grizzle.LintSeed(safeSQL)
		if len(diags) != 0 {
			t.Fatalf("expected 0 diagnostics for safe seed SQL, got: %+v", diags)
		}
	})

	t.Run("unsafe patterns flagged with L012", func(t *testing.T) {
		unsafeSQL := `
			INSERT INTO users (id, name) VALUES (1, 'alice');
			TRUNCATE TABLE audit_log;
			DELETE FROM tokens;
		`
		diags := grizzle.LintSeed(unsafeSQL)
		if len(diags) != 3 {
			t.Fatalf("expected 3 diagnostics, got %d: %+v", len(diags), diags)
		}

		for _, d := range diags {
			if d.RuleID != "L012" {
				t.Errorf("expected RuleID L012, got %s", d.RuleID)
			}
			if d.Severity != grizzle.LintSeverityWarning {
				t.Errorf("expected Severity WARNING, got %s", d.Severity)
			}
		}

		if grizzle.LintHasErrors(diags) {
			t.Errorf("LintHasErrors should be false for WARNING diagnostics")
		}
	})
}

func TestCompileSchema_AttachesSeedSQLAndLints(t *testing.T) {
	db, err := sql.Open("sqlite", ":memory:")
	if err != nil {
		t.Fatalf("opening sqlite: %v", err)
	}
	defer func() { _ = db.Close() }()

	opts := grizzle.Options{
		Dialect:   grizzle.DialectSQLite,
		SchemaSQL: "CREATE TABLE users (id INTEGER PRIMARY KEY, name TEXT);",
		SeedSQL:   "INSERT INTO users (id, name) VALUES (1, 'root');",
	}

	ir, err := grizzle.CompileSchema(context.Background(), db, opts)
	if err != nil {
		t.Fatalf("CompileSchema failed: %v", err)
	}
	if ir.SeedSQL != opts.SeedSQL {
		t.Fatalf("expected ir.SeedSQL = %q, got %q", opts.SeedSQL, ir.SeedSQL)
	}

	diags := grizzle.LintSchema(ir)
	var l012Found bool
	for _, d := range diags {
		if d.RuleID == "L012" {
			l012Found = true
			if d.Table != "users" {
				t.Errorf("expected Table 'users', got %q", d.Table)
			}
		}
	}
	if !l012Found {
		t.Errorf("expected L012 diagnostic from LintSchema on compiled schema with SeedSQL")
	}
}
